import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {digest,canonicalJson,snapshotFlirtSources,verifyFlirtContentReview} from './lib/flirt-content-audit.mjs';
import {createVariationContext} from './lib/pabo-variation-context.mjs';
const [code,dir]=process.argv.slice(2);
assert.match(code||'',/^[A-D]\d{2}$/,'Gebruik: npm run flirt:replace -- C02 /pad/naar/goedgekeurd-pakket');
assert.ok(dir,'Publicatiepakket ontbreekt');
const names=['flirt.mp4','poster.jpg','captions.vtt','transcript.html'];
const bytes=Object.fromEntries(names.map(n=>[n,fs.readFileSync(path.join(dir,n))]));
assert.ok(bytes['flirt.mp4'].length < 24*1024*1024,'Publicatiepakket: film moet kleiner zijn dan 24 MiB; gebruik de vooraf goedgekeurde lichte versie.');
const metadata=JSON.parse(fs.readFileSync(path.join(dir,'metadata.json'),'utf8'));
const suppliedReview=JSON.parse(fs.readFileSync(path.join(dir,'review.json'),'utf8'));
assert.equal(metadata.approved,true,'Pakket mist de vastgelegde filmgoedkeuring');
assert.equal(typeof metadata.captionsBurnedIn,'boolean','Leg vast of de ondertitels zijn ingebrand');
assert.ok(['embedded','legacy'].includes(metadata.audioMode),'Leg de audiokeuze vast');
for(const field of ['expectedMisconception','intendedInsight','observedContent','captionEvidence']) assert.ok(typeof suppliedReview[field]==='string'&&suppliedReview[field].length>=15,`Review mist ${field}`);
assert.ok(['aligned','aligned-with-notes','mismatch'].includes(suppliedReview.verdict),'Review mist het inhoudelijke oordeel');
assert.ok(Array.isArray(suppliedReview.visualEvidence)&&suppliedReview.visualEvidence.length,'Review mist beeldmomenten');
assert.ok(Array.isArray(suppliedReview.notes),'Review mist kanttekeningen');
assert.match(bytes['transcript.html'].toString(),/<meta\s+name=["']viewport["']/i,'Transcript mist mobiele viewport');
assert.ok(bytes['captions.vtt'].toString().trimStart().startsWith('WEBVTT'),'Ondertitels moeten WEBVTT zijn');
const info=JSON.parse(execFileSync('ffprobe',['-v','error','-show_entries','format=duration:stream=codec_type','-of','json',path.join(dir,'flirt.mp4')],{encoding:'utf8',timeout:30000}));
const duration=Number(info.format.duration);assert.ok(duration>=15&&duration<=600,'Ongeldige duur');
assert.ok(info.streams.some(s=>s.codec_type==='video'),'Videostream ontbreekt');
if(metadata.audioMode==='embedded')assert.ok(info.streams.some(s=>s.codec_type==='audio'),'Ingebedde stem ontbreekt');
const catalogPath='public/assets/data/grabbelton-videos.json',reviewPath='public/assets/data/flirt-content-review.json';
const catalog=JSON.parse(fs.readFileSync(catalogPath)),review=JSON.parse(fs.readFileSync(reviewPath));
const item=catalog.videos.find(v=>v.target.misconceptionCode===code);assert.ok(item,'Onbekende flirtcode');
const previous=review.entries.find(v=>v.code===code);assert.ok(previous,'Bestaande beoordeling ontbreekt');
const sameMedia=names.every(n=>fs.existsSync(`public/films/rekenklaar/${code}/${n}`)&&digest(fs.readFileSync(`public/films/rekenklaar/${code}/${n}`))===digest(bytes[n]));
const sameMetadata=item.audioMode===metadata.audioMode&&item.captionsBurnedIn===metadata.captionsBurnedIn&&(!metadata.summary||metadata.summary===item.summary)&&(!metadata.title||metadata.title===item.title);
const sameReview=Object.entries(suppliedReview).every(([k,v])=>canonicalJson(previous[k])===canonicalJson(v));
if(sameMedia&&sameMetadata&&sameReview){console.log(`${code}: dit goedgekeurde pakket staat al in de bron; niets opnieuw vervangen.`);process.exit(0);}
const release=`roadie-${code.toLowerCase()}-${digest(Buffer.concat(names.map(n=>bytes[n]))).slice(0,16)}`;
Object.assign(item,{durationSeconds:Math.round(duration),release,audioMode:metadata.audioMode,captionsBurnedIn:metadata.captionsBurnedIn});
if(metadata.summary)item.summary=metadata.summary;
if(metadata.title)item.title=metadata.title;
const today=new Date().toISOString().slice(0,10);catalog.updatedAt=today;
const context=createVariationContext(fs.readFileSync('public/apps/pabo-rekenklaar/index.html','utf8'));
const destination=`public/films/rekenklaar/${code}`;
const changes=new Map(names.map(n=>[`${destination}/${n}`,bytes[n]]));
changes.set(catalogPath,Buffer.from(JSON.stringify(catalog,null,2)+'\n'));
const originals=new Map([...changes.keys(),reviewPath].map(p=>[p,fs.existsSync(p)?fs.readFileSync(p):null]));
try {
 for(const [p,b] of changes)fs.writeFileSync(p,b);
 const snapshot=snapshotFlirtSources(process.cwd(),catalog,context.PaboRekenklaarQA.MISCONCEPTION_CATALOG,[code]);
 const updated={...previous,...suppliedReview,code,videoId:item.id,title:item.title,fingerprints:snapshot[0].fingerprints};
 review.entries[review.entries.findIndex(e=>e.code===code)]=updated;review.reviewedAt=today;
 const result=verifyFlirtContentReview({...review,entries:[updated]},snapshot,[code]);assert.ok(result.passed,result.failures.join('\n'));
 fs.writeFileSync(reviewPath,JSON.stringify(review,null,2)+'\n');
 fs.mkdirSync('.release',{recursive:true});
 fs.writeFileSync('.release/package.json',JSON.stringify({code,release,duration,approved:true,files:Object.fromEntries(names.map(n=>[n,digest(bytes[n])])),next:'release:prepare -- --base=<main-sha>'},null,2)+'\n');
 console.log(`${code}: goedgekeurd pakket geplaatst (${duration.toFixed(3)} s), metadata en vingerafdrukken bijgewerkt. Geen spelercode of rekenaudit gewijzigd.`);
} catch(error) {
 for(const [p,b] of originals)if(b===null)fs.rmSync(p,{force:true});else fs.writeFileSync(p,b);
 throw error;
}
