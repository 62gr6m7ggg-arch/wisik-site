import assert from 'node:assert/strict';
import fs from 'node:fs';
import {classifyPaths,fullModules} from './release-policy.mjs';
import {planForPaths} from './classify-release-change.mjs';
import {commandsForPlan} from './release-commands.mjs';
import {paboHtmlPath,paboSourceManifest} from './lib/pabo-source.mjs';
import {validateReportChanges} from './lib/release-reports.mjs';
let count=0;
const expect=(paths,expected)=>{assert.deepEqual(classifyPaths(paths).modules,[...expected].sort());count++};
expect(['public/films/rekenklaar/A04/flirt.mp4','public/assets/data/grabbelton-videos.json'],['media']);
expect(['public/assets/js/pabo-flirt-player.js'],['player']);
expect(['public/assets/js/grabbelton.js'],['player']);
expect(['public/assets/js/grabbelton-core.js'],['player']);
expect([paboHtmlPath],['pabo-ui']);
expect(['public/apps/pabo-rekenklaar/wisik-bridge.css'],['pabo-ui']);
expect(['src/pabo/variation-generators.js'],['pabo','player','pabo-ui']);
expect(['scripts/lib/flirt-chain-audit.mjs'],['pabo','player','pabo-ui']);
expect(['tests/flirt-cases.json'],['pabo','player','pabo-ui']);
expect(['public/apps/meetkunde/app.js'],['meetkunde']);
expect(['public/rafelrand/sinus-s-en-de-geit/mixer.js'],['gonio']);
expect(['public/rafelrand/konijnenhol/Hoogstaand_Diepgaan.mp4'],['konijnenhol']);
expect(['public/apps/ruimteklaar/assets/app.js'],['space']);
expect(['docs/publicatieproces.md'],[]);
expect(['scripts/verify-publication.mjs'],['delivery']);
expect(['tests/gonio_integrity.py'],['delivery','gonio']);
expect(['public/apps/meetkunde/app.js','public/films/rekenklaar/A04/flirt.mp4'],['meetkunde','media']);
for(const p of ['scripts/release-policy.mjs','.github/workflows/quality.yml'])expect([p],fullModules);
for(const p of ['public/films/rekenklaar/A04/injected.js','new-unknown-module/code.js','public/apps/new-module/index.html'])assert.throws(()=>classifyPaths([p]),/Geen modulekoppeling/);
const html=fs.readFileSync(paboHtmlPath,'utf8');
const read=file=>fs.readFileSync(file,'utf8');
const plan=(paths,changes={})=>planForPaths(paths,{readBefore:read,readAfter:p=>changes[p]??read(p)});
const noMath=p=>{
 assert.ok(!p.modules.includes('pabo'));
 assert.ok(!commandsForPlan(p).some(([command])=>/audit-pabo|pabo-didactic|test-pabo-(rich|flirts|variation|reasoning)/.test(command)),JSON.stringify(p));count++;
};
const movie=plan(['public/films/rekenklaar/A04/flirt.mp4']);
assert.deepEqual(movie.codes,['A04']);noMath(movie);
noMath(plan(['public/assets/js/pabo-flirt-player.js']));
noMath(plan([paboHtmlPath],{[paboHtmlPath]:html.replace('<title>','<title>Presentatie ')}));
const modifiedMath=plan([paboHtmlPath],{[paboHtmlPath]:html.replace('"use strict";','"use strict";\nconst changedCalculation=true;')});
assert.ok(modifiedMath.modules.includes('pabo'),'Gewijzigde appcode mag nooit de rekentests overslaan');
const changedLoader=plan([paboHtmlPath],{[paboHtmlPath]:html.replace('</head>','<script src="/new-math.js"></script></head>')});
assert.ok(changedLoader.modules.includes('pabo'),'Een extra afhankelijkheid moet expliciet worden beoordeeld');
const catalog=JSON.parse(read('public/assets/data/grabbelton-videos.json'));
catalog.videos.find(v=>v.target.misconceptionCode==='A04').summary+=' Nieuwe film.';
const metadata=plan(['public/assets/data/grabbelton-videos.json'],{'public/assets/data/grabbelton-videos.json':JSON.stringify(catalog)});
assert.deepEqual(metadata.codes,['A04']);noMath(metadata);
const mixed=plan(['public/films/rekenklaar/A04/flirt.mp4','public/apps/meetkunde/app.js']);
assert.deepEqual(mixed.codes,['A04']);noMath(mixed);
const sharedMedia=plan(['public/films/rekenklaar/A04/flirt.mp4','scripts/test-roadie-release.mjs']);
assert.deepEqual(sharedMedia.codes,[],'Een wijziging aan gedeelde mediacontroles moet alle films omvatten');
const changedPackage=JSON.parse(read('package.json'));changedPackage.version='0.1.999';
noMath(plan(['package.json'],{'package.json':JSON.stringify(changedPackage)}));
changedPackage.scripts.check='node changed-check.mjs';
assert.ok(plan(['package.json'],{'package.json':JSON.stringify(changedPackage)}).modules.includes('pabo'));
const root=process.cwd(),baseline=paboSourceManifest(root);
const altered=(suffix,transform)=>paboSourceManifest(root,{read:file=>{const data=fs.readFileSync(file);return file.endsWith(suffix)?transform(data.toString()):data}});
assert.deepEqual(altered(paboHtmlPath,s=>s.replace('<title>','<title>Andere opmaak ')),baseline,'Presentatie mag rekenbewijs niet ongeldig maken');
assert.deepEqual(altered('pabo-flirt-player.js',s=>s+'\n// andere ondertitelinstelling'),baseline,'Speler mag rekenbewijs niet ongeldig maken');
assert.notDeepEqual(altered(paboHtmlPath,s=>s.replace('"use strict";','"use strict";\nconst changedMath=1;')),baseline);
assert.notDeepEqual(altered('variation-generators.js',s=>s+'\n// changed'),baseline);
assert.notDeepEqual(altered('audit-pabo-release.mjs',s=>s+'\n// changed test'),baseline);
assert.ok(!Object.keys(baseline.files).some(p=>/grabbelton|player|films\//.test(p)));
assert.deepEqual(validateReportChanges(['public/assets/data/pabo-release-audit.json'],{status:'passed',modules:['pabo']}),['public/assets/data/pabo-release-audit.json']);
assert.throws(()=>validateReportChanges(['public/assets/js/grabbelton.js'],{status:'passed',modules:['pabo']}));
assert.throws(()=>validateReportChanges(['public/assets/data/pabo-release-audit.json'],{status:'failed',modules:['pabo']}));
assert.throws(()=>validateReportChanges(['public/assets/data/pabo-release-audit.json'],{status:'passed',modules:['media']}));
const commands=commandsForPlan({modules:fullModules,codes:[]});
assert.equal(commands.length,new Set(commands.map(c=>c.join(' '))).size,'Geen dubbele commando’s in een vrijgave');
console.log(`Releasegrenzen geslaagd: ${count} selecties, bronbinding en negatieve gevallen; film/speler/opmaak starten nul rekentests.`);
